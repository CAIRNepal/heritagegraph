#!/usr/bin/env node
/**
 * Generate a deterministic, font-independent icon set for the heritage-museum
 * node types from @tabler/icons (MIT, 24×24 outline glyphs).
 *
 * Why: the museum previously used emoji as node icons, which render differently
 * on every OS/browser and can't be reproduced in a publication figure. This
 * bakes real vector path data into `node-icons.generated.ts`, consumed both as
 * a React component and as an SVG string (Leaflet/D3) so every surface renders
 * identically everywhere.
 *
 * Re-run after changing the mapping below:  node scripts/gen-node-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ICON_DIR = join(__dirname, '..', 'node_modules', '@tabler', 'icons', 'icons', 'outline');
const OUT = join(__dirname, '..', 'src', 'app', '(dashboard)', 'heritage-museum', 'node-icons.generated.ts');

// NodeType (from the generated ontology viz config) → Tabler outline glyph name.
// Keep in sync with NODE_TYPE_CONFIG keys. Semantically negotiable: yin-yang, star.
const MAP = {
  Place: 'map-pin',
  Temple: 'building-arch',
  BuddhistMonument: 'building-monument',
  ArchitecturalStructure: 'building',
  Settlement: 'building-community',
  Deity: 'flower',
  Festival: 'flame',
  TimeSpan: 'hourglass',
  ReligiousTradition: 'yin-yang',
  SacredSite: 'star',
  Person: 'user',
  Guthi: 'users',
  IconographicObject: 'photo',
  HistoricalPeriod: 'history',
  Source: 'books',
  HistoricalEvent: 'calendar-event',
};

/** Strip the outer <svg> wrapper, keep the inner path markup, collapse whitespace. */
function innerMarkup(svg) {
  return svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    // Tabler ships a transparent bounding-box path; harmless but we drop it.
    .replace(/<path stroke="none"[^/]*\/>/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

const inner = {};
const names = {};
for (const [type, glyph] of Object.entries(MAP)) {
  const file = join(ICON_DIR, `${glyph}.svg`);
  inner[type] = innerMarkup(readFileSync(file, 'utf8'));
  names[type] = glyph;
}

const banner = `// AUTO-GENERATED by scripts/gen-node-icons.mjs — DO NOT EDIT.
// Source: @tabler/icons (MIT). Re-run the script to regenerate.
`;
const body =
  banner +
  '\nexport const NODE_ICON_INNER: Record<string, string> = ' +
  JSON.stringify(inner, null, 2) +
  ';\n\n/** Tabler glyph name per type — for figure legends / documentation. */\n' +
  'export const NODE_ICON_GLYPH: Record<string, string> = ' +
  JSON.stringify(names, null, 2) +
  ';\n';

writeFileSync(OUT, body);
console.log(`✓ wrote ${Object.keys(inner).length} node icons → ${OUT.split('/heritage_graph_ui/')[1]}`);
